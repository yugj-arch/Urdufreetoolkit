# -*- coding: utf-8 -*-
"""Build the neural transliterator's training data from free, human-authored
sources (see ``data/SOURCES.md``):

* Wiktionary Urdu (kaikki.org dump)   -- Urdu word + inflections + roman (+ Hindi spelling)
* Wiktionary Hindi (kaikki.org dump)  -- Hindi word + inflections + roman; Urdu spelling
  either given by the entry or generated by ``deva_to_urdu_candidates`` and kept
  only when a real Urdu corpus attests it
* Aksharantar Urdu (AI4Bharat)        -- 700k Urdu word -> casual roman pairs
* Dakshina Urdu (Google Research)     -- romanisation lexicon + 10k word-aligned
  romanised sentences; its Wikipedia text is the attestation corpus

Outputs (``data/translit_ds/``):

  train.tsv / dev.tsv   task \\t src \\t tgt \\t weight
                        task j: urdu -> "R|devanagari"   (both known; Devanagari
                                conditioned on the Roman reading, so they agree)
                        task r: urdu -> R                (Devanagari unknown)
                        task c: urdu -> casual roman     (Aksharantar / Dakshina)
                        task h: R -> devanagari          (Hindi Wiktionary, 85k:
                                Hindi orthography for readings the lexicon has
                                no Devanagari for)
  test.jsonl            held-out gold words {urdu, R, deva, src}
  lexicon_train.json    gold lexicon without the test words (for honest eval)
  lexicon_full.json     gold lexicon over everything (what ships)
  evidence_*.json.gz    urdu -> {casual roman: weight} (top 3) from Aksharantar/Dakshina
                        (runtime beam reranking; _train omits held-out words)
  stats.json

Run:  python -m training.translit.build_data
"""
from __future__ import annotations

import argparse
import collections
import gzip
import hashlib
import json
import random
import re
import unicodedata
import zipfile
from pathlib import Path

import difflib

from urdu_nn.scheme import (
    deva_to_urdu_candidates, fold_roman, is_urdu_word, norm_urdu, to_plain, wik_to_rich,
)

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "translit_raw"
OUT = ROOT / "data" / "translit_ds"
DAK = RAW / "dakshina_dataset_v1.0" / "ur"

_DEVA = re.compile(r"^[ऀ-ॿ]+$")
_CASUAL = re.compile(r"^[a-z]+$")


def _isur(s: str) -> bool:
    return any("؀" <= c <= "ۿ" for c in s)


def _bucket(key: str) -> float:
    return int(hashlib.md5(key.encode("utf-8")).hexdigest()[:8], 16) / 0xFFFFFFFF


# ---------------------------------------------------------------------------
# attestation corpus
# ---------------------------------------------------------------------------

def attested_counts() -> collections.Counter:
    cnt: collections.Counter = collections.Counter()
    tok = re.compile(r"[؀-ۿٰٔ]+")
    for name in ("ur.wiki-filt.train.text.shuf.txt.gz", "ur.wiki-filt.valid.text.shuf.txt.gz"):
        p = DAK / "native_script_wikipedia" / name
        if not p.exists():
            continue
        with gzip.open(p, "rt", encoding="utf-8") as fh:
            for line in fh:
                for w in tok.findall(line):
                    cnt[norm_urdu(w)] += 1
    for p in (ROOT / "training" / "corpus").glob("*.txt"):
        for line in p.read_text(encoding="utf-8").splitlines():
            for w in tok.findall(line):
                cnt[norm_urdu(w)] += 1
    return cnt


