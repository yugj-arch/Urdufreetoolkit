def _pairs_from_phrase(urdu: str, roman: str):
    """Split a multi-word (urdu, roman) into word pairs when counts line up."""
    us = urdu.split()
    rs = re.split(r"[ \-]", roman)
    rs = [r for r in rs if r]
    if len(us) == len(rs):
        return list(zip(us, rs))
    if len(us) == 1:
        return [(urdu, roman.replace("-", ""))]
    return []


def hindi_roman_map():
    """R (from Hindi Wiktionary romanisation) -> Devanagari, most frequent."""
    r2d: dict[str, collections.Counter] = {}
    with open(RAW / "kaikki_hi.jsonl", encoding="utf-8") as fh:
        for line in fh:
            e = json.loads(line)
            items = []
            for f in e.get("forms", []):
                form = f.get("form", "")
                if f.get("roman") and _DEVA.match(form):
                    items.append((form, f["roman"], 1))
                if "romanization" in f.get("tags", []) and _DEVA.match(e["word"]):
                    items.append((e["word"], form, 5))   # headword beats table cells
            for deva, rom, w in items:
                rich = wik_to_rich(rom, source="hi")
                if rich and " " not in rich:
                    r2d.setdefault(rich, collections.Counter())[unicodedata.normalize("NFC", deva)] += w
    return {r: c.most_common(1)[0][0] for r, c in r2d.items()}


def urdu_wiktionary(r2d):
    """Yield dict(urdu, voc, rich, deva, lemma, kind)."""
    with open(RAW / "kaikki_ur.jsonl", encoding="utf-8") as fh:
        for line in fh:
            e = json.loads(line)
            word = e.get("word", "")
            if not _isur(word):
                continue
            lemma = "ur:" + norm_urdu(word)
            forms = e.get("forms", [])
            rom = next((f["form"] for f in forms if "romanization" in f.get("tags", [])), None)
            hi = next((f["form"] for f in forms if "Hindi" in f.get("tags", [])
                       and _DEVA.match(f.get("form", ""))), None)
            canon = next((f["form"] for f in forms if "canonical" in f.get("tags", [])
                          and _isur(f.get("form", ""))), word)
            if rom:
                for u, r in _pairs_from_phrase(canon, rom):
                    rich = wik_to_rich(r, u, "ur")
                    if rich and " " not in rich and is_urdu_word(norm_urdu(u, keep_harakat=True)):
                        deva = hi if (hi and " " not in canon and " " not in rom) else r2d.get(rich)
                        yield dict(urdu=norm_urdu(u), voc=norm_urdu(u, True), rich=rich,
                                   deva=deva, lemma=lemma, kind="lemma")
            for f in forms:
                form, r = f.get("form", ""), f.get("roman")
                if not r or not _isur(form) or "،" in form or "," in r:
                    continue
                for u, rr in _pairs_from_phrase(form, r):
                    rich = wik_to_rich(rr, u, "ur")
                    if rich and " " not in rich and is_urdu_word(norm_urdu(u, keep_harakat=True)):
                        yield dict(urdu=norm_urdu(u), voc=norm_urdu(u, True), rich=rich,
                                   deva=r2d.get(rich), lemma=lemma, kind="form")
            for s in e.get("senses", []):
                for x in s.get("examples", []):
                    t, r = x.get("text", ""), x.get("roman", "")
                    if not (_isur(t) and r):
                        continue
                    t = re.sub(r"[۔،؟!?.,:;\"'«»()]", " ", t)
                    r = re.sub(r"[?!.,:;\"«»()]", " ", r)
                    for u, rr in _pairs_from_phrase(" ".join(t.split()), " ".join(r.split())):
                        rich = wik_to_rich(rr, u, "ur")
                        if rich and is_urdu_word(norm_urdu(u, keep_harakat=True)):
                            yield dict(urdu=norm_urdu(u), voc=norm_urdu(u, True), rich=rich,
                                       deva=r2d.get(rich), lemma=lemma, kind="example")


def _stem(urdu: str) -> str:
    for suf in ("نا", "ا", "ہ", "ی", "ے", "ں"):
        if urdu.endswith(suf) and len(urdu) - len(suf) >= 2:
            return urdu[: -len(suf)]
    return urdu


def hindi_wiktionary(att: collections.Counter, min_att: int, known: set[str]):
    """Yield dict(urdu, voc, rich, deva, lemma, kind) from Hindi entries."""
    with open(RAW / "kaikki_hi.jsonl", encoding="utf-8") as fh:
        for line in fh:
            e = json.loads(line)
            word = unicodedata.normalize("NFC", e.get("word", ""))
            if not _DEVA.match(word):
                continue
            forms = e.get("forms", [])
            rom = next((f["form"] for f in forms if "romanization" in f.get("tags", [])), None)
            ur = next((f["form"] for f in forms if "Urdu" in f.get("tags", [])
                       and _isur(f.get("form", "")) and " " not in f["form"].strip()), None)
            lemma = "hi:" + word
            items = []
            if rom:
                items.append((word, rom, "lemma"))
            for f in forms:
                form = unicodedata.normalize("NFC", f.get("form", ""))
                if f.get("roman") and _DEVA.match(form) and form != word:
                    items.append((form, f["roman"], "form"))
            ur_n = norm_urdu(ur) if ur else None
            stem = _stem(ur_n) if ur_n else None
            seen = set()
            for deva, r, kind in items:
                if deva in seen:
                    continue
                seen.add(deva)
                rich = wik_to_rich(r, source="hi")
                if not rich or " " in rich:
                    continue
                if kind == "lemma" and ur_n:
                    yield dict(urdu=ur_n, voc=norm_urdu(ur, True), rich=rich, deva=deva,
                               lemma=lemma, kind="hi-lemma-ur")
                    continue
                cands = deva_to_urdu_candidates(deva)
                if not cands:
                    continue
                if stem:
                    on_stem = [c for c in cands if c.startswith(stem)]
                    best = max(on_stem, key=lambda c: att.get(c, 0)) if on_stem else None
                    if best and att.get(best, 0) >= 1:
                        yield dict(urdu=best, voc=best, rich=rich, deva=deva,
                                   lemma=lemma, kind="hi-form-ur")
                    continue
                best = max(cands, key=lambda c: att.get(c, 0))
                # a generated spelling that collides with a real Urdu headword
                # is far more likely that word than this Hindi one (دیو = dev)
                if att.get(best, 0) >= min_att and len(best) >= 3 and best not in known:
                    yield dict(urdu=best, voc=best, rich=rich, deva=deva,
                               lemma=lemma, kind="hi-attested")


